applied_count = 0

for city, city_updates in updates.items():
    if city not in cat:
        print(f"Warning: {city} not in catalog.json")
        continue
    for card in cat[city]:
        bucket = card.get("bucket")
        if bucket in city_updates:
            new_info = city_updates[bucket]
            old_title = card["title"]
            card["title"] = new_info["title"]
            card["body"] = new_info["body"]
            print(f"✓ [{city}] [{bucket}]: '{old_title}' -> '{new_info['title']}'")
            applied_count += 1

with open(CAT_PATH, "w", encoding="utf-8") as f:
    json.dump(cat, f, ensure_ascii=False, indent=2)

print(f"\nSuccessfully updated {applied_count} cards across {len(updates)} cities in catalog.json!")
